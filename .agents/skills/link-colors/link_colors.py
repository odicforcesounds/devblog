#!/usr/bin/env python3
"""Colour every link on the blog by where it points.

Three kinds, three colours, so a reader can tell at a glance what leaves the blog:

    local     a page of this blog        docs/*.html, ./x, images/x,
                                         https://blog.odicforcesounds.com/x.html
    art       https://art.odicforcesounds.com/...   (the art site, backups/art_map.json)
    external  anything else that starts with http or https

In-page anchors (`#order-…`), `mailto:` and `javascript:` keep the page's own colour:
they do not go anywhere new.

The rules live in one generated sheet, `docs/link-colors.css`, and every page links it
as its last stylesheet, so it wins the cascade and also works on pages that never load
`article.css`. It is a same-origin file, so a policy that allows `'self'` styles keeps
working without `'unsafe-inline'`.

    python3 .agents/skills/link-colors/link_colors.py            # write the sheet + links
    python3 .agents/skills/link-colors/link_colors.py --dry-run   # report only
    python3 .agents/skills/link-colors/link_colors.py --check     # verify, exit 1 on drift
    python3 .agents/skills/link-colors/link_colors.py --remove    # take the links out
"""

import argparse
import glob
import json
import os
import re
import sys

DOCS = "docs"
FRONT = "index.html"
SHEET = os.path.join(DOCS, "link-colors.css")
ART_MAP = os.path.join("backups", "art_map.json")
FALLBACK_ART_HOST = "art.odicforcesounds.com"

LOCAL = "#6fb3ff"
ART = "#ffd23f"
EXTERNAL = "#ff9ecb"
HOVER = "#ffffff"

LINK_TAG = re.compile(r'\n?[ \t]*<link rel="stylesheet" href="/?link-colors\.css"[^>]*>', re.I)

SHEET_CSS = """/* Generated by .agents/skills/link-colors/link_colors.py: colour by destination. */

:root {
  --link-local: %(local)s;
  --link-art: %(art)s;
  --link-external: %(external)s;
  --link-hover: %(hover)s;
}

a[href^="http"]:not([href*="odicforcesounds.com"]) {
  color: var(--link-external) !important;
}

a[href*="odicforcesounds.com"]:not([href*="%(art_host)s"]):not([href^="mailto:"]),
a[href^="./"],
a[href^="images/"],
a[href$=".html"],
a[href*=".html#"] {
  color: var(--link-local) !important;
}

a[href*="%(art_host)s"] {
  color: var(--link-art) !important;
}

a[href]:hover,
a[href]:focus-visible {
  color: var(--link-hover) !important;
}
"""

SHEET_CSS = re.sub(r"/\*.*?\*/", "", SHEET_CSS, flags=re.S)
SHEET_CSS = re.sub(r"\n{3,}", "\n\n", SHEET_CSS).strip() + "\n"


def art_host():
    """The art site as backups/art_map.json records it, without the scheme."""
    try:
        with open(ART_MAP, encoding="utf-8") as handle:
            site = json.load(handle).get("site") or ""
    except Exception:
        return FALLBACK_ART_HOST
    host = re.sub(r"^https?://", "", site).strip("/")
    return host or FALLBACK_ART_HOST


def classify(href, host):
    """Which of the three colours a link gets; None when it keeps the page's own."""
    value = (href or "").strip()
    if not value or value.startswith("#") or value.startswith("mailto:") \
            or value.lower().startswith("javascript:"):
        return None
    if host in value:
        return "art"
    if value.startswith("http"):
        if "odicforcesounds.com" in value:
            return "local"
        return "external"
    return "local"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Colour links by destination.")
    parser.add_argument("--dry-run", action="store_true", help="report only")
    parser.add_argument("--check", action="store_true", help="verify, write nothing")
    parser.add_argument("--remove", action="store_true", help="take the links out")
    args = parser.parse_args(argv)

    host = art_host()
    pages = sorted(p for p in glob.glob(os.path.join(DOCS, "*.html"))
                   if os.path.basename(p) != FRONT)
    if not pages:
        print("no pages found", file=sys.stderr)
        return 1

    sheet = SHEET_CSS % {"local": LOCAL, "art": ART, "external": EXTERNAL,
                         "hover": HOVER, "art_host": host}
    counts = {"local": 0, "art": 0, "external": 0, "neutral": 0}
    missing = []
    unlinked = []
    written = removed = 0

    for path in pages:
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as handle:
            source = handle.read()
        for href in re.findall(r'<a[^>]*href="([^"]*)"', source, re.I):
            kind = classify(href, host)
            counts[kind or "neutral"] += 1

        body = LINK_TAG.sub("", source)
        if args.remove:
            if body != source:
                if not args.check and not args.dry_run:
                    with open(path, "w", encoding="utf-8") as handle:
                        handle.write(body)
                removed += 1
            continue

        if args.check:
            if 'link-colors.css' not in source:
                missing.append(name)
            continue

        href = "/link-colors.css" if name == "404.html" else "link-colors.css"
        tag = '  <link rel="stylesheet" href="%s">\n' % href
        updated = body.replace("</head>", tag + "</head>", 1)
        if updated == body:
            unlinked.append(name)
            continue
        if updated != source:
            if not args.dry_run:
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(updated)
            written += 1

    print("art host: %s (from %s)" % (host, ART_MAP))
    print("links: local %d | art %d | external %d | kept as written %d"
          % (counts["local"], counts["art"], counts["external"], counts["neutral"]))

    if args.check:
        stale = []
        if os.path.exists(SHEET):
            with open(SHEET, encoding="utf-8") as handle:
                if handle.read() != sheet:
                    stale.append(SHEET)
        else:
            stale.append(SHEET)
        print("pages: %d | without the link: %d | sheet out of date: %d"
              % (len(pages), len(missing), len(stale)))
        for name in missing[:10]:
            print("  missing link:", name)
        for name in stale:
            print("  stale sheet:", name)
        return 1 if (missing or stale) else 0

    if args.remove:
        print("links removed: %d | pages: %d" % (removed, len(pages)))
        return 0

    if not args.dry_run:
        with open(SHEET, "w", encoding="utf-8") as handle:
            handle.write(sheet)
    print("stylesheet: %s (%d bytes)" % (SHEET, len(sheet)))
    print("pages written: %d | without a head: %d" % (written, len(unlinked)))
    if args.dry_run:
        print("dry run — nothing was written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
