CSS = re.sub(r"/\*.*?\*/", "", CSS, flags=re.S)
CSS = re.sub(r"\n{3,}", "\n\n", CSS).strip() + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="One improved stylesheet for the article pages.")
    parser.add_argument("--dry-run", action="store_true", help="report only")
    parser.add_argument("--check", action="store_true", help="verify, write nothing")
    args = parser.parse_args(argv)

    pages = [p for p in sorted(glob.glob(os.path.join(DOCS, "*.html")))
             if os.path.basename(p) != FRONT]

    served = [p for p in pages if ARTICLE.search(open(p, encoding="utf-8").read())]
    swapped = skipped = 0

    for path in pages:
        with open(path, encoding="utf-8") as handle:
            source = handle.read()
        updated = ARTICLE.sub(lambda m: m.group(1) + PAGE_LINK, source)
        if updated == source:
            continue
        if args.check:
            skipped += 1
            continue
        if not args.dry_run:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(updated)
        swapped += 1

    sheet_matches = os.path.exists(SHEET) and open(SHEET, encoding="utf-8").read() == CSS

    if args.check:
        print("pages: %d | still loading article.css: %d | sheet current: %s"
              % (len(pages), len(served), "yes" if sheet_matches else "no"))
        for path in served[:10]:
            print("  still on article.css:", os.path.basename(path))
        return 1 if served or not sheet_matches else 0

    if not args.dry_run:
        with open(SHEET, "w", encoding="utf-8") as handle:
            handle.write(CSS)
    print("stylesheet: %s (%d bytes)" % (SHEET, len(CSS)))
    print("pages that loaded article.css: %d" % len(served))
    print("links swapped: %d%s" % (swapped, " (dry run)" if args.dry_run else ""))
    if args.dry_run:
        print("nothing was written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
